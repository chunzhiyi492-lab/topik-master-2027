test('production PWA reopens a saved mock offline and auto-submits an expired exam once', async ({ page, context }) => {
  const start = Date.parse('2026-11-09T15:59:30Z')
  await page.clock.setFixedTime(start)
  await context.route(FONTS, route => route.abort())
  await page.goto('./#/practice')
  await page.waitForFunction(() => !!navigator.serviceWorker.controller)
  const title = '隔离离线模考卷'
  await page.locator('input[type=file]').setInputFiles({
    name: 'offline-exam.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({
      papers: [{ title, source: '隔离测试' }],
      questions: [{ paperTitle: title, qtype: '阅读', stem: '离线试题', order: 1, source: '隔离测试',
        options: ['첫째', '둘째'], answerIndex: 0, status: '已核实' }],
    })),
  })
  await page.getByRole('button', { name: '确认导入', exact: true }).click()
  await expect(page.getByRole('heading', { name: '题库导入结果' })).toBeVisible()
  await page.goto('./#/mock')
  await page.getByRole('combobox', { name: '选择试卷' }).selectOption({ label: title })
  await page.getByRole('radio', { name: '只练阅读' }).check()
  await page.getByRole('spinbutton', { name: /阅读时长/ }).fill('1')
  await page.getByRole('button', { name: '开始模拟考试' }).click()
  await page.getByRole('button', { name: 'A. 첫째', exact: true }).click()
  await expect(page.getByText('已选：A')).toBeVisible()
  await page.close()

  await context.setOffline(true)
  const resumed = await context.newPage()
  await resumed.clock.setFixedTime(start + 31_000)
  await resumed.goto('./#/mock')
  await expect(resumed.getByText('已选：A')).toBeVisible()
  await expect(resumed.getByText(/剩余 00:29/)).toBeVisible()
  await resumed.close()

  const expired = await context.newPage()
  await expired.clock.setFixedTime(start + 90_000)
  await expired.goto('./#/mock')
  await expect(expired.getByRole('heading', { name: '成绩（#15）' })).toBeVisible()
  await expired.reload()
  await expect(expired.getByText('历史成绩（1 场）')).toBeVisible()
  await expect(expired.getByRole('row', { name: '答对 1 道' })).toBeVisible()
  await expired.goto('./')
  await expired.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '个人中心' }).click()
  await expired.getByRole('link', { name: '学习统计与日历' }).click()
  await expect(expired.getByRole('row', { name: /模考交卷 1 场/ })).toBeVisible()
  await expect(expired.getByRole('row', { name: /客观题作答 1 次/ })).toContainText('计分 1 次')
  await expect(expired.getByRole('region', { name: /学习明细/ })).toContainText('模考交卷 1 场')
  expect(await expired.evaluate(() => navigator.onLine)).toBe(false)
})
