test('写作只有数据库写成功才显示保存，写失败保留原文并可重试', async ({ page }) => {
  await seed(page, ['写作'])
  await page.goto('./#/practice')
  await page.getByRole('button', { name: '开始练习', exact: true }).click()
  const input = page.locator('textarea')
  await input.fill(draft)
  // 挡住实际 IndexedDB 写入：失败时必须等到 Promise 拒绝才显示错误。
  await page.evaluate(async (moduleUrl) => {
    const { db } = await import(moduleUrl)
    window.testAddAttempt = db.attempts.add.bind(db.attempts)
    db.attempts.add = () => db.constructor.waitFor(new Promise((_resolve, reject) => {
      window.testRejectAttempt = () => reject(new Error('注入的写入失败'))
    }))
  }, dbModule)
  await page.getByRole('button', { name: '保存答案', exact: true }).click()
  await expect(page.getByText('已保存：答案与用时已记录，刷新后还在。')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '保存答案', exact: true })).toBeDisabled()
  await page.waitForFunction(() => typeof window.testRejectAttempt === 'function')
  await page.evaluate(() => window.testRejectAttempt())
  await expect(page.getByRole('alert')).toContainText('注入的写入失败')
  await expect(input).toHaveValue(draft)
  await expect(page.getByText('已保存：答案与用时已记录，刷新后还在。')).toHaveCount(0)
  await page.evaluate(async (moduleUrl) => {
    const { db } = await import(moduleUrl)
    db.attempts.add = window.testAddAttempt
  }, dbModule)
  await page.getByRole('button', { name: '保存答案', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  const rows = await page.evaluate(async (moduleUrl) => (await import(moduleUrl)).db.attempts.toArray(), dbModule)
  expect(rows).toHaveLength(1)
  expect(rows[0]).toMatchObject({ selectedAnswer: draft, subjective: true })
  await page.reload()
  await page.getByRole('button', { name: '开始练习', exact: true }).click()
  await expect(input).toHaveValue(draft)
})

