// 连续天数规则单测（周日不算断签）。开发时用，不进仓库流程。
// 用法：node scripts/test-streak.mjs
import { calcStreak } from '../src/lib/streak.ts';

const d = (s) => new Date(s + 'T12:00:00');
const cases = [
  // [名称, 打卡日（YYYY-MM-DD）, 今天, 期望]
  ['空记录', [], '2026-11-08', 0],
  ['只今天', ['2026-11-08'], '2026-11-08', 1],
  ['只昨天', ['2026-11-07'], '2026-11-08', 1],
  ['昨天未学算断', ['2026-11-06'], '2026-11-08', 0],
  ['周六→周一连续（周日不算断）', ['2026-11-07', '2026-11-09'], '2026-11-09', 2],
  ['周日缺勤不算断', ['2026-11-06', '2026-11-07', '2026-11-09'], '2026-11-09', 3],
  ['周日打卡也算', ['2026-11-07', '2026-11-08', '2026-11-09'], '2026-11-09', 3],
  ['普通连续 3 天', ['2026-11-06', '2026-11-07', '2026-11-09'], '2026-11-09', 3],
  ['今天未学但昨天学过', ['2026-11-07'], '2026-11-08', 1],
  ['重复打卡去重', ['2026-11-08', '2026-11-08'], '2026-11-08', 1],
];

let pass = 0;
for (const [name, days, today, want] of cases) {
  const got = calcStreak(days, d(today));
  const ok = got === want;
  if (ok) pass++;
  console.log(`${ok ? 'PASS' : 'FAIL'} ${name}: got ${got}, want ${want}`);
}
console.log(`${pass}/${cases.length} 通过`);
process.exit(pass === cases.length ? 0 : 1);
